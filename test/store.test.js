process.env.DB_PATH='./data/test-nexora.db';
process.env.SESSION_SECRET='test-only-session-secret';
const {test,after}=require('node:test');
const assert=require('node:assert/strict');
const request=require('supertest');
const app=require('../server');
const db=app.locals.db;
after(()=>{db.close();for(const suffix of ['','-shm','-wal']){try{require('fs').unlinkSync('./data/test-nexora.db'+suffix)}catch{}}});
test('customer journey: catalog, signup, cart, checkout, and private orders',async()=>{
  const customer=request.agent(app);
  const stranger=request.agent(app);
  const home=await request(app).get('/').expect(200).expect('Content-Type',/html/);
  assert.match(home.text,/NEXORA/);
  assert.match(home.text,/id="modal-wrap"/);
  await request(app).get('/css/styles.css').expect(200).expect('Content-Type',/css/);
  await request(app).get('/js/app.js').expect(200).expect('Content-Type',/javascript/);
  await request(app).get('/images/image-unavailable.svg').expect(200).expect('Content-Type',/svg/);
  const catalog=await request(app).get('/api/products').expect(200);
  assert.ok(catalog.body.total>=120);
  const categories=(await request(app).get('/api/categories').expect(200)).body;
  assert.equal(categories.length,12);
  for(const category of categories){
    const result=await request(app).get('/api/products').query({category:category.slug}).expect(200);
    assert.ok(result.body.total>0,`${category.name} has products`);
  }
  assert.ok(catalog.body.items[0].review_count>=0);
  assert.doesNotThrow(()=>JSON.parse(catalog.body.items[0].specifications));
  assert.equal((await request(app).get('/api/products?search=QuietComfort').expect(200)).body.total,1);
  assert.ok((await request(app).get('/api/products?category=mobiles&sort=price_asc').expect(200)).body.items.length>0);
  const firstPage=await request(app).get('/api/products?page=1&limit=12&sort=price_asc').expect(200);
  const secondPage=await request(app).get('/api/products?page=2&limit=12&sort=price_asc').expect(200);
  assert.equal(firstPage.body.items.length,12);
  assert.notEqual(firstPage.body.items[0].id,secondPage.body.items[0].id);
  assert.ok(firstPage.body.items[0].finalPrice<=firstPage.body.items[1].finalPrice);
  await request(app).get('/api/products/999999').expect(404);
  await request(app).get('/api/products/not-an-id').expect(404);
  await request(app).get('/api/cart').expect(401);
  await customer.post('/api/register').send({name:'Demo Customer',email:'demo@example.com',password:'NexoraPass123'}).expect(201);
  await customer.post('/api/register').send({name:'Duplicate',email:'demo@example.com',password:'NexoraPass123'}).expect(409);
  await customer.post('/api/logout').expect(200);
  await customer.get('/api/cart').expect(401);
  await customer.post('/api/login').send({email:'demo@example.com',password:'NexoraPass123'}).expect(200);
  const item=catalog.body.items.find(p=>p.stock>0);
  await customer.post('/api/cart').send({productId:item.id,quantity:1}).expect(200);
  await customer.post('/api/cart').send({productId:item.id,quantity:1}).expect(200);
  const cart=(await customer.get('/api/cart').expect(200)).body;
  assert.equal(cart.items.length,1);
  assert.equal(cart.items[0].quantity,2);
  assert.equal(cart.gross,item.price*2);
  await customer.patch('/api/cart/'+item.id).send({quantity:1}).expect(200);
  assert.equal((await customer.get('/api/cart').expect(200)).body.items[0].quantity,1);
  await customer.post('/api/cart').send({productId:item.id,quantity:item.stock+1}).expect(400);
  const shipping={name:'Demo Customer',email:'demo@example.com',phone:'5551234567',address:'1 Demo Street',city:'Portland',postalCode:'97201'};
  const checkoutKey='customer-checkout-attempt-0001';
  const placed=await customer.post('/api/checkout').send({...shipping,idempotencyKey:checkoutKey,subtotal:0,total:0}).expect(201);
  assert.ok(placed.body.orderNumber.startsWith('NX-'));
  assert.equal(placed.body.total,item.finalPrice);
  const repeated=await customer.post('/api/checkout').send({...shipping,idempotencyKey:checkoutKey}).expect(200);
  assert.equal(repeated.body.id,placed.body.id);
  assert.equal(repeated.body.duplicate,true);
  const orders=(await customer.get('/api/orders').expect(200)).body;
  assert.equal(orders.length,1);
  const detail=await customer.get('/api/orders/'+placed.body.id).expect(200);
  assert.equal(detail.body.items.length,1);
  assert.equal(detail.body.total,placed.body.total);
  assert.equal((await customer.get('/api/cart').expect(200)).body.items.length,0);
  assert.equal(db.prepare('SELECT stock FROM products WHERE id=?').get(item.id).stock,item.stock-1);
  await stranger.post('/api/register').send({name:'Other Customer',email:'other@example.com',password:'NexoraPass123'}).expect(201);
  assert.equal((await stranger.get('/api/orders').expect(200)).body.length,0);
  await stranger.get('/api/orders/'+placed.body.id).expect(404);
});

